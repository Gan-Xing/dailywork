type ReplacementFn = (match: string, ...groups: string[]) => string
type Replacement = [RegExp, string | ReplacementFn]

const roadNumberLabel = (road: string, suffix = '') => {
  const parsed = Number.parseInt(road, 10)
  const roadLabel = Number.isFinite(parsed) ? String(parsed) : road.replace(/^0+/, '')
  return `阿尼比莱克鲁${roadLabel}${suffix.trim().toUpperCase()}号路`
}

const applyReplacements = (value: string, replacements: Replacement[]) =>
  replacements.reduce((text, [pattern, replacement]) => {
    if (typeof replacement === 'string') return text.replace(pattern, replacement)
    return text.replace(pattern, (match: string, ...args: unknown[]) => {
      const groups = args.slice(0, -2).map((arg) => String(arg ?? ''))
      return replacement(match, ...groups)
    })
  }, value)

